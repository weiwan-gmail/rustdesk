export function isLetterUsbHid(usbHid: number): boolean {
  return usbHid >= 0x04 && usbHid <= 0x1D;
}

export function isNumpadUsbHid(usbHid: number): boolean {
  return (usbHid >= 0x54 && usbHid <= 0x63) || usbHid === 0x67 || usbHid === 0x85;
}

export type FlutterMapKey =
  | { kind: "pause" }
  | { kind: "map"; chr: number };

/** Map Flutter usbHidUsage&0xFFFF to the code the host injects in KeyboardMode.Map. */
export function mapUsbHidToPeerCode(usbHid: number, peerPlatform: string): number | undefined {
  const hid = usbHid & 0xffff;
  const p = (peerPlatform || "").toLowerCase();
  if (p === "windows") {
    return USB_HID_TO_WIN_SCANCODE[hid];
  }
  if (p === "linux") {
    return USB_HID_TO_LINUX_KEYCODE[hid];
  }
  if (p === "macos" || p === "mac os" || p === "mac os x" || p === "darwin") {
    const code = USB_HID_TO_MAC_KEYCODE[hid];
    // kVK_ANSI_A is 0 — a valid code, not a missing mapping.
    return code;
  }
  return USB_HID_TO_LINUX_KEYCODE[hid] ?? USB_HID_TO_WIN_SCANCODE[hid];
}

export function flutterKeyModifiers(usbHid: number, lockModes: number): Array<"CapsLock" | "NumLock"> {
  const mods: Array<"CapsLock" | "NumLock"> = [];
  const hid = usbHid & 0xffff;
  // Matches src/keyboard.rs parse_add_lock_modes_modifiers (CAPS_LOCK=1, NUM_LOCK=2).
  if (isLetterUsbHid(hid) && (lockModes & (1 << 1)) !== 0) mods.push("CapsLock");
  if (isNumpadUsbHid(hid) && (lockModes & (1 << 2)) !== 0) mods.push("NumLock");
  return mods;
}

export function flutterHidToMapKey(usbHid: number, peerPlatform: string): FlutterMapKey | undefined {
  const hid = usbHid & 0xffff;
  const p = (peerPlatform || "").toLowerCase();
  // Windows has no usable Pause scan code; native sends Legacy ControlKey.Pause.
  if (hid === USB_HID_PAUSE && p === "windows") {
    return { kind: "pause" };
  }
  const chr = mapUsbHidToPeerCode(hid, peerPlatform);
  if (chr === undefined) return undefined;
  return { kind: "map", chr };
}

